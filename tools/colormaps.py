"""Dump matplotlib colormaps as Rust tables into src/colormap.rs."""
import matplotlib

MAPS = ["viridis", "berlin"]
STEPS = 256


def table(name: str) -> str:
    cmap = matplotlib.colormaps[name]
    rows = []
    for i in range(STEPS):
        r, g, b, _ = cmap(i / (STEPS - 1), bytes=True)
        rows.append(f"[{r}, {g}, {b}]")
    lines = [", ".join(rows[i:i + 5]) for i in range(0, STEPS, 5)]
    body = ",\n    ".join(lines)
    const = name.upper()
    return f"pub const {const}: Colormap = [\n    {body},\n];\n"


header = f'''//! Colormaps sampled from matplotlib. Generated by tools/colormaps.py.
use crate::image::{{Color, mix}};

pub type Colormap = [Color; {STEPS}];

/// Color at t in 0..1, clamped, linearly interpolated.
pub fn sample(map: &Colormap, t: f64) -> Color {{
    let x = t.clamp(0.0, 1.0) * (map.len() - 1) as f64;
    let i = (x.floor() as usize).min(map.len() - 2);
    mix(map[i], map[i + 1], x - i as f64)
}}

'''
with open("src/colormap.rs", "w") as out:
    out.write(header + "\n".join(table(m) for m in MAPS))
